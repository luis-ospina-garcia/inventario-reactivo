CREATE TABLE product (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku   VARCHAR(50)  NOT NULL,
    name  VARCHAR(200) NOT NULL,
    stock INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT uk_product_sku UNIQUE (sku),
    CONSTRAINT ck_product_stock CHECK (stock >= 0)
);

CREATE TABLE movement (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT      NOT NULL,
    type       VARCHAR(10) NOT NULL,
    quantity   INTEGER     NOT NULL,
    reason     VARCHAR(200),
    created_at TIMESTAMP   NOT NULL,
    CONSTRAINT fk_movement_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT ck_movement_quantity CHECK (quantity > 0),
    CONSTRAINT ck_movement_type CHECK (type IN ('IN', 'OUT'))
);

CREATE INDEX idx_movement_product ON movement (product_id);
